package com.itheima.literal;

public class LiteralDemo1 {
    public static void main(String[] args) {
        //输出恐龙的信息：霸王龙 8岁 公//
        //输出恐龙的名称：霸王龙
        System.out.println("霸王龙");
        //输出恐龙的年龄：8
        System.out.println(8);
        //输出恐龙的性别：公
        System.out.println("公");
    }


}
/*字面量：程序中的数据，直接表示数据值的符号
分类及用法
1. 数值字面量：直接写数字，包含整数和小数
   例如：8、-8、8.8、-8.8、8.8E2、-8.8e2
2. 字符字面量：要用单引号括起来，有且只有一个字符
   例如：'a'、'A'、'1'、' '、'@'
3. 字符串字面量：直接写字符串
   例如："Hello World"、"123"、" "
4. 布尔字面量：表示真假，直接写
   例如：true、false
5. 空字面量：表示空，直接写
   例如：null
*/