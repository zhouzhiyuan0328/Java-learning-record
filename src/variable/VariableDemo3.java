package variable;

public class VariableDemo3 {
    public static void main(String[] args) {
    /*
    定义8中数据类型变量：

    整数：byte, short, int, long
    浮点数：float, double
    字符：char
    布尔：boolean

    定义格式： 数据类型 变量名 = 数据值;
     */

//        1.定义一个byte变量，初始值为10
        byte a = 10;

//        定义一个short变量，初始值为10
        short b = 10;

//        定义一个int变量，初始值为10
        int c = 10;

//        定义一个long变量，初始值为10
        //long类型要加一个L
        long d = 22L;

//        定义一个float变量，初始值为10
        //float类型要加一个F
        float e = 10.0F;

//        定义一个double变量，初始值为10
        double f = 10.0;

//        定义一个char变量，初始值为'A'
        char g = '中';

//        定义一个boolean变量，初始值为true
        boolean h = true;
    }

}
